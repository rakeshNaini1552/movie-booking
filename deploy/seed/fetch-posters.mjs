// Downloads a poster for every movie in catalog-movies.sql from TMDB into frontend/public/posters/
// and writes catalog-posters.sql, which sets poster_url for those movies.
//
//   TMDB_API_KEY=... node deploy/seed/fetch-posters.mjs            (run from the repo root)
//   node deploy/seed/fetch-posters.mjs --dry-run                   (parse the seed only, no network)
//
// Safe to run again: a poster file that already exists is not downloaded twice.
// TMDB_API_KEY can be the short "API Key" or the long "API Read Access Token". It is never printed.
import { mkdir, readFile, writeFile, access } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const seedFile = join(here, "catalog-movies.sql");
const outFile = join(here, "catalog-posters.sql");
const postersDir = join(here, "..", "..", "frontend", "public", "posters");
const dryRun = process.argv.includes("--dry-run");

// Rows look like: ('Finding Nemo', 100, 'English', 'G', 2003)
const rowPattern = /^\s*\('((?:[^']|'')+)',\s*(\d+),\s*'[^']*',\s*'[^']*',\s*(\d{4})\)/;

const slugOf = (title) =>
  title.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const movies = (await readFile(seedFile, "utf8"))
  .split("\n")
  .map((line) => rowPattern.exec(line))
  .filter(Boolean)
  .map((m) => ({ title: m[1].replaceAll("''", "'"), year: m[3] }))
  .map((m) => ({ ...m, slug: slugOf(m.title) }));

console.log(`${movies.length} movies found in ${seedFile}`);
if (dryRun) {
  for (const m of movies.slice(0, 10)) console.log(`  ${m.title} (${m.year}) -> ${m.slug}.jpg`);
  const dupes = movies.map((m) => m.slug).filter((s, i, all) => all.indexOf(s) !== i);
  console.log(dupes.length ? `duplicate slugs: ${[...new Set(dupes)].join(", ")}` : "no duplicate slugs");
  process.exit(0);
}

const key = process.env.TMDB_API_KEY;
if (!key) {
  console.error("Set TMDB_API_KEY first (export TMDB_API_KEY=...).");
  process.exit(1);
}
const bearer = key.startsWith("eyJ");
const headers = bearer ? { Authorization: `Bearer ${key}` } : {};

async function search(title, year) {
  const params = new URLSearchParams({ query: title, year, include_adult: "false" });
  if (!bearer) params.set("api_key", key);
  const response = await fetch(`https://api.themoviedb.org/3/search/movie?${params}`, { headers });
  if (response.status === 401) throw new Error("TMDB rejected the key (401). Check TMDB_API_KEY.");
  if (!response.ok) throw new Error(`TMDB search failed: ${response.status}`);
  const { results } = await response.json();
  return results.find((r) => r.poster_path) ?? null;
}

const exists = (path) => access(path).then(() => true, () => false);
await mkdir(postersDir, { recursive: true });

const done = [];
const missing = [];
for (const movie of movies) {
  const file = join(postersDir, `${movie.slug}.jpg`);
  if (!(await exists(file))) {
    const hit = await search(movie.title, movie.year).catch((error) => {
      if (error.message.includes("401")) throw error;
      return null;
    });
    if (!hit) {
      missing.push(movie.title);
      continue;
    }
    const image = await fetch(`https://image.tmdb.org/t/p/w500${hit.poster_path}`);
    if (!image.ok) {
      missing.push(movie.title);
      continue;
    }
    await writeFile(file, Buffer.from(await image.arrayBuffer()));
    await new Promise((resolve) => setTimeout(resolve, 120)); // stay well under TMDB's rate limit
    console.log(`downloaded ${movie.slug}.jpg`);
  }
  done.push(movie);
}

const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const values = done.map((m) => `  (${quote(m.title)}, ${quote(`/posters/${m.slug}.jpg`)})`).join(",\n");
await writeFile(
  outFile,
  `-- Generated by fetch-posters.mjs. Sets poster_url for movies that have a poster file; safe to run again.
-- Run like the movie seed:
--   docker compose exec -T catalog-postgres sh -c 'psql -v ON_ERROR_STOP=1 --single-transaction -U "$POSTGRES_USER" -d "$POSTGRES_DB"' < seed/catalog-posters.sql
UPDATE movie SET poster_url = v.url
FROM (VALUES
${values}
) AS v(title, url)
WHERE lower(movie.title) = lower(v.title) AND movie.poster_url IS DISTINCT FROM v.url;

SELECT count(*) AS movies_with_poster FROM movie WHERE poster_url IS NOT NULL;
`,
);
console.log(`\n${done.length} posters ready, ${missing.length} not found.`);
if (missing.length) console.log(`No poster for: ${missing.join("; ")}`);
console.log(`Wrote ${outFile}`);
